import assert from 'node:assert/strict'
import { history, pathOf, picks, rub } from './marker.js'

const r = (left, top, right, bottom) => ({ left, top, right, bottom })
const circle = r(100, 100, 300, 200)

assert.equal(picks(r(150, 140, 250, 160), circle), true, 'a line fully inside')
assert.equal(picks(r(0, 0, 50, 50), circle), false, 'far away')
assert.equal(picks(r(280, 150, 600, 170), circle), false, 'a line barely touched at its start')
assert.equal(picks(r(0, 0, 1000, 1000), circle), true, 'a circle inside part of a big output or chart')
assert.equal(picks(r(90, 120, 200, 140), circle), true, 'center inside, edge sticking out')
console.log('marker checks passed')

const line = { tone: 'red', pts: [[0, 0], [10, 0], [20, 0], [30, 0], [40, 0], [50, 0]] }
assert.deepEqual(rub([line], [25, 0], 8).map((s) => s.pts), [[[0, 0], [10, 0], [17, 0]], [[33, 0], [40, 0], [50, 0]]], 'rubbed through the middle')
assert.deepEqual(rub([line], [25, 0], 4).map((s) => s.pts), [[[0, 0], [10, 0], [20, 0], [21, 0]], [[29, 0], [30, 0], [40, 0], [50, 0]]], 'cut inside one segment')
assert.deepEqual(rub([{ tone: 'red', pts: [[0, 0], [100, 0]] }], [50, 3], 5).map((s) => s.pts), [[[0, 0], [46, 0]], [[54, 0], [100, 0]]], 'a fast two-point stroke keeps both halves')
assert.deepEqual(rub([line], [25, 100], 8), [line], 'rubbed elsewhere')
assert.deepEqual(rub([line], [25, 0], 100), [], 'rubbed out completely')
assert.deepEqual(rub([line], [0, 0], 8).map((s) => s.pts[0]), [[8, 0]], 'rubbed one end')
assert.deepEqual(rub([line], [25, 0], 8)[0].tone, 'red', 'pieces keep their colour')
assert.equal(pathOf([[1, 2], [3, 4]]), 'M1 2 L3 4')
assert.equal(pathOf([[0, 0], [10, 0], [20, 10], [30, 10]]), 'M0 0 Q10 0 15 5 Q20 10 25 10 L30 10', 'smoothed through midpoints, ending on the last point')
console.log('eraser checks passed')

let h = history.start([])
h = history.change(h, ['a'])
h = history.change(h, ['a', 'b'])
h = history.change(h, ['a'])
h = history.replace(h, [])
assert.deepEqual(h.now, [])
h = history.undo(h)
assert.deepEqual(h.now, ['a', 'b'], 'undo takes back the whole rub')
h = history.undo(h)
assert.deepEqual(h.now, ['a'])
h = history.redo(h)
assert.deepEqual(h.now, ['a', 'b'])
h = history.change(h, ['a', 'b', 'c'])
assert.deepEqual(history.redo(h), h, 'nothing to redo after a new change')
assert.deepEqual(history.undo(history.start(['x'])).now, ['x'], 'nothing to undo at the start')
let long = history.start([])
for (let i = 0; i < 150; i++) long = history.change(long, [i])
assert.equal(long.past.length, 100, 'history is capped')
console.log('history checks passed')
